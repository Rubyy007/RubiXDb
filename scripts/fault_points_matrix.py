#!/usr/bin/env python3
"""Builds docs/CRASH_CLASS_MATRIX.md from the TSV files the executed fault-point tests wrote under
target/fault-points-results/ (tests/fault_points/). Nothing in the matrix is typed by hand: every row is a case that ran.

    cargo build --features fault-points --example fault_child
    cargo test  --features fault-points --test fault_points -- --test-threads=1
    python scripts/fault_points_matrix.py [--date YYYY-MM-DD] [--base <git hash>]

Class C and class D sections are emitted EMPTY on purpose (awaiting D1b / D1c): D1a produces class A and class B only.
"""
import argparse
import collections
import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "target" / "fault-points-results"


def load(name):
    p = RES / name
    if not p.exists():
        return None
    with open(p, encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f, delimiter="\t"))
    head, body = rows[0], rows[1:]
    return [dict(zip(head, r)) for r in body]


def load_plain(name):
    """Header-ful TSV whose header is plain text (coverage.tsv)."""
    p = RES / name
    if not p.exists():
        return None
    with open(p, encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f, delimiter="\t"))
    return [dict(zip(rows[0], r)) for r in rows[1:]]


def esc(s, n=None):
    s = (s or "").replace("|", "\\|").replace("\n", " ")
    if n and len(s) > n:
        s = s[: n - 1] + "…"
    return s


def short_state(s):
    # keep only the file names of the interesting directories, drop sizes of long lists
    return esc(s, 150)


def single_writer_section(rows, out):
    by_point = collections.OrderedDict()
    for r in rows:
        by_point.setdefault((r["point"], r["scenario"]), []).append(r)
    out.append("| point | workload | abort at 1st hit | abort at later hit | pause + `Child::kill()` at 1st hit | stopped mid-operation (all runs) | state the stop left (1st-hit abort) |")
    out.append("|---|---|---|---|---|---|---|")
    for (point, scen), rs in by_point.items():
        first = next((r for r in rs if r["stop"].startswith("abort") and r["trigger"].startswith("once")), None)
        later = next((r for r in rs if r["stop"].startswith("abort") and r["trigger"].startswith("nth=")), None)
        kill = next((r for r in rs if r["stop"].startswith("pause")), None)
        dist = all(r["distinguishable_from_clean_stop"].split(";")[0].endswith("absent") for r in rs)

        def cell(r):
            if r is None:
                return "—"
            t = r["trigger"].split(" ")[0]
            return f"{r['verdict']} ({t})"

        out.append(
            f"| `{point}` | {scen} | {cell(first)} | {cell(later)} | {cell(kill)} | {'yes' if dist else 'NO'} | {short_state(first['state_at_stop'] if first else '')} |"
        )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", default="")
    ap.add_argument("--base", default="")
    ap.add_argument("--out", default=str(ROOT / "docs" / "CRASH_CLASS_MATRIX.md"))
    a = ap.parse_args()

    single = load("class_b_single_writer.tsv")
    conc = load("class_b_concurrent.tsv")
    rel = load("class_b_relational.tsv")
    cls_a = load("class_a.tsv")
    cov = load_plain("coverage.tsv")
    missing = [n for n, v in (("class_b_single_writer.tsv", single), ("class_b_concurrent.tsv", conc), ("class_b_relational.tsv", rel), ("class_a.tsv", cls_a)) if v is None]
    if missing:
        sys.exit(f"missing result files (run the tests first): {missing}")

    def counts(rows):
        c = collections.Counter(r["verdict"] for r in rows)
        return f"{c.get('PASS', 0)} PASS / {c.get('FAIL', 0)} FAIL of {len(rows)}"

    out = []
    w = out.append
    w("# rubiXDb — CRASH CLASS MATRIX (D1a)")
    w("")
    w(f"Generated by `scripts/fault_points_matrix.py` from the result files written by `tests/fault_points/` {('on ' + a.date) if a.date else ''}"
      f"{(' against base commit ' + a.base) if a.base else ''}. Every row below is a case that was executed; none is typed by hand. "
      "Platform: Windows 10 Home 10.0.19045, NTFS, SATA SSD, debug build, `rustc 1.98.1`. Nothing was run on Linux/macOS.")
    w("")
    w("## 0. Read this first")
    w("")
    w("* **Kill-9 is not power-loss evidence.** Every class B row is a *process* death: the operating system and its page cache survive, so every byte a returned `write()` handed over is visible to the next process whether or not it was ever synced. A missing `fsync` is therefore **invisible** to every row in section 2. No class B result appears, or may be copied, in a class C (power-loss) column.")
    w("* **Class A** (section 1): an `error=` action makes the call site's `Result` an `Err` while the process lives; the engine's real failure path runs. Supports error-path claims only.")
    w("* **Class C** (simulated power loss) and **class D** (storage error preventing recovery): sections 3 and 4 are **empty**: the D1c matrix has not been run (D1b built the simulator and a *smoke* cycle - `docs/PERSISTENCE_MODEL.md` §7 - which is not this matrix). There is no power-loss capability on this platform (Windows `fsync_dir` is a no-op; no `dm-flakey`, no hardware cut rig). **Power loss: NOT TESTED.**")
    w("* Expected state for every class A/B row (docs/DURABILITY_CONTRACT.md §8): recovery succeeds (or refuses fail-closed, class D), and the recovered keyspace equals `model(K)` per writer for some `K` with `acked <= K <= submitted` (R1–R4, R12); the first post-recovery write is numbered above every acknowledged seq and the checkpoint (R6); a second recovery changes nothing (R10); the stopped, recovered directory passes the physical checker (R7/R8) and has no leftover `*.sst.tmp` (R11). R5 is **not** independently observable at key-value level (only the engine's own `RecoveryStats` identity is checked). The oracle is independent of the engine under test: expected data is regenerated from the seed and from the child's ledger of submitted/acknowledged operations; it compares every key and value, never counts.")
    w("* A row is PASS only if the execution log names the requested point, the process was stopped there (abort status, or parked and killed by the parent), **and** the oracle accepted the recovered state. `POINT NOT REACHED` and `KILL TIMEOUT` are FAIL.")
    w("")
    w("## 1. Class A — returned I/O error, process alive")
    w("")
    w(f"Result: **{counts(cls_a)}**. Trigger: `error=other` at the 1st hit (non-engine workloads) or at a later hit (engine workload). *Observation* is what the child process did.")
    w("")
    w("| point | workload | trigger | observation | oracle |")
    w("|---|---|---|---|---|")
    for r in cls_a:
        obs = r["distinguishable_from_clean_stop"].replace("n/a (class A: the process lives); ", "")
        w(f"| `{r['point']}` | {r['scenario']} | {esc(r['trigger'].split(' ')[0])} | {esc(obs, 230)} | {r['verdict']} |")
    na = RES / "class_a_not_applicable.txt"
    if na.exists():
        w("")
        w("Points whose call site has no `Result` to carry an error (an `error=` rule on them is rejected at parse time rather than silently ignored): " + ", ".join(f"`{x}`" for x in na.read_text().split()) + ".")
    w("")
    w("## 2. Class B — process kill")
    w("")
    w("**Every row in this section is crash class B — process kill. Kill-9 is not power-loss evidence.**")
    w("")
    w("### 2.1 Single writer, product configuration (GroupCommit 5 ms / 256 KiB)")
    w("")
    w(f"Result: **{counts(single)}**. *abort* = the process aborts itself at the point; *pause + kill* = the process parks at the point and the parent terminates it (`TerminateProcess`) — an external kill at a deterministic instruction.")
    w("")
    single_writer_section(single, out)
    w("")
    w("### 2.2 Four concurrent writers, seeded-probabilistic trigger (`prob=P,seed=S`)")
    w("")
    f = [r for r in conc if r["verdict"] != "PASS"]
    sig = [r for r in f if "F-D1a-1 SIGNATURE on all" in r["detail"]]
    w(f"Result: **{counts(conc)}**. Failing rows: {len(f)}; of those carrying the automatic **F-D1a-1 signature** (an acknowledged write whose seq is at or below the manifest checkpoint yet present in no live SSTable): {len(sig)}; **without** it: {len(f) - len(sig)}.")
    w("")
    w("**These rows fail because of a pre-existing engine defect (F-D1a-1, `OPEN_ITEMS.md`), not because of the rig**: it reproduces on a pristine export of `dde8ae9` with no fault-point code, without any fault rule, and across a *graceful* stop (docs/D0_BASELINE.md, D1a section). The rows are reported as they came out; a PASS here does not show the defect absent (it is timing-dependent), a FAIL shows an acknowledged write lost. Reproducibility is per hit index, not per thread interleaving (ADR-FAULTPOINTS-01 §5.3).")
    w("")
    w("| point | trigger | verdict | detail |")
    w("|---|---|---|---|")
    for r in conc:
        w(f"| `{r['point']}` | {esc(r['trigger'].split(' ')[0])} | {r['verdict']} | {esc(r['detail'], 300) if r['verdict'] != 'PASS' else ''} |")
    w("")
    w("### 2.3 Relational workload (rows + secondary-index entries through `TableStore`), single writer")
    w("")
    w(f"Result: **{counts(rel)}**. Judged by (1) the decoded-row model and (2) a raw-keyspace differential against a never-crashed reference (catches a row without its index entry, a dangling index entry, catalog damage). SQL text is above this layer and is not exercised.")
    w("")
    w("| point | trigger | verdict |")
    w("|---|---|---|")
    for r in rel:
        w(f"| `{r['point']}` | {esc(r['trigger'].split(' ')[0])} | {r['verdict']} |")
    nr = RES / "relational_not_reached.txt"
    if nr.exists() and nr.read_text().strip():
        w("")
        w("Engine points the relational workload never reaches (not counted as passed): " + ", ".join(f"`{x}`" for x in nr.read_text().split()) + ".")
    w("")
    w("### 2.4 Points with no class B row")
    w("")
    if cov:
        for r in cov:
            if r["status"] == "Unreachable":
                w(f"* `{r['point']}` — **Unreachable** (verified: never hit by any workload). See the status table in ADR-FAULTPOINTS-01 §12.1 for the reason.")
    w("")
    w("## 3. Class C — simulated power loss")
    w("")
    w("*Awaiting D1c. The D1b simulator, its four proof tests and a smoke cycle exist (`docs/PERSISTENCE_MODEL.md` §6, §7; rows in `target/sim-power-loss-results/smoke.tsv`, each labelled \"crash class C - SIMULATED power loss\"); the matrix over every fault point does not. No class B result may be placed here.*")
    w("")
    w("| point | expected | observed | verdict |")
    w("|---|---|---|---|")
    w("| *(none — D1b has not been run)* | | | |")
    w("")
    w("## 4. Class D — storage error preventing recovery")
    w("")
    w("*Awaiting D1b/D1c. No class D result exists* (corrupted-fixture and fault-during-recovery cases are D1c scope; section 2 rows at `startup.*`, `wal.tail_truncate`, `manifest.tail_truncate` and `lsm.sweep_*` are class B/A kills of recovery steps, not class D).")
    w("")
    w("| fixture / point | expected | observed | verdict |")
    w("|---|---|---|---|")
    w("| *(none)* | | | |")
    w("")
    w("## 5. Where the evidence is thin (kept visible)")
    w("")
    w("* Torn-tail fixtures (`recover/TornWalTail`, `recover/TornManifestTail`) and the stale-file fixtures are **synthetic** bytes appended by the test, not states observed after a crash.")
    w("* A kill between two `write_all` calls leaves a prefix; it does not model a single write torn inside a sector (class C).")
    w("* Windows `fsync_dir` is a no-op, so the `*.dir_sync` points kill before/after a call that does nothing on this platform; the state they leave is still the ordering state, but no durability claim follows.")
    w("* The concurrent column is non-deterministic and currently exposes F-D1a-1 (above).")
    w("")
    pathlib.Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {a.out}: A {counts(cls_a)}; B single {counts(single)}; B concurrent {counts(conc)}; B relational {counts(rel)}")


if __name__ == "__main__":
    main()
